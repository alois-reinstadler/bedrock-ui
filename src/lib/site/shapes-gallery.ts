/** Export the rendered artwork; serialization is a documentation feature. */
export function serializeShape(element: SVGSVGElement | null, color: string, rotation: number) {
	if (!element) throw new Error('Shape preview is not ready');
	const svg = element.cloneNode(true) as SVGSVGElement;
	svg.removeAttribute('class');
	svg.removeAttribute('style');
	svg.removeAttribute('data-slot');
	svg.setAttribute('width', '256');
	svg.setAttribute('height', '256');
	svg.setAttribute('fill', color);
	const group = document.createElementNS('http://www.w3.org/2000/svg', 'g');
	group.setAttribute('transform', `rotate(${rotation} 128 128)`);
	group.append(...Array.from(svg.childNodes));
	svg.append(group);
	return new XMLSerializer().serializeToString(svg);
}
